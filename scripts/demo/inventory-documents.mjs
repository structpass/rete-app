export function assetPublishedAt(key, versionIndex) {
  if (['baseline', 'minutes'].includes(key)) return '2026-10-30T16:10:00+09:00';
  if (key === 'screens')
    return versionIndex ? '2026-10-30T16:35:00+09:00' : '2026-10-29T16:00:00+09:00';
  if (key === 'csv')
    return versionIndex ? '2026-10-30T15:25:00+09:00' : '2026-10-29T16:00:00+09:00';
  const times = {
    questions: '14:25',
    quantity: '10:30',
    agenda: '16:30',
    orders: '09:00',
    errors: '14:45',
    locations: '15:00',
    profiling: '11:10',
  };
  return '2026-10-30T' + (times[key] ?? '15:45') + ':00+09:00';
}
